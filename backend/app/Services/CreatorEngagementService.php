    // Aggregates
    // =================================================================

    /**
     * Normalise and bound a reporting window.
     *
     * @return array{from:string,to:string,days:int}
     */
    public static function window(?string $from = null, ?string $to = null): array
    {
        $to   = self::normaliseDate($to) ?? date('Y-m-d');
        $from = self::normaliseDate($from) ?? date('Y-m-d', strtotime($to . ' -' . (self::DEFAULT_WINDOW_DAYS - 1) . ' days'));

        if ($from > $to) {
            [$from, $to] = [$to, $from];
        }

        $days = (int) floor((strtotime($to) - strtotime($from)) / 86400) + 1;

        if ($days > self::MAX_WINDOW_DAYS) {
            $from = date('Y-m-d', strtotime($to . ' -' . (self::MAX_WINDOW_DAYS - 1) . ' days'));
            $days = self::MAX_WINDOW_DAYS;
        }

        return ['from' => $from, 'to' => $to, 'days' => $days];
    }

    /** A calendar date, or null for anything that is not one. */
    private static function normaliseDate(?string $value): ?string
    {
        $value = trim((string) $value);

        if ($value === '' || preg_match('/^\d{4}-\d{2}-\d{2}$/', $value) !== 1) {
            return null;
        }

        [$y, $m, $d] = array_map('intval', explode('-', $value));

        return checkdate($m, $d, $y) ? $value : null;
    }

    /**
     * Event totals for a creator over a window, presented against the
     * catalogue so every event type appears — with a zero — rather than being
     * absent and looking like a bug in the dashboard.
     *
     * An event type whose term has since been retired is appended at the end
     * instead of dropped. Dropping it would leave `total` disagreeing with the
     * sum of the breakdown, and a total that does not add up destroys trust in
     * the whole screen.
     *
     * @return array{from:string,to:string,days:int,total:int,by_type:list<array<string,mixed>>}
     */
    public static function totals(int $creatorId, ?string $from = null, ?string $to = null): array
    {
        $window = self::window($from, $to);

        $counts = [];

        foreach (Database::select(
            'SELECT `event_type`, COUNT(*) AS `total`
               FROM `creator_engagement_events`
              WHERE `creator_id` = :c AND `occurred_on` BETWEEN :from AND :to
              GROUP BY `event_type`',
            ['c' => $creatorId, 'from' => $window['from'], 'to' => $window['to']]
        ) as $row) {
            $counts[(string) $row['event_type']] = (int) $row['total'];
        }

        $byType = [];
        $total  = 0;

        foreach (self::catalogue() as $value => $definition) {
            $count = $counts[$value] ?? 0;
            unset($counts[$value]);

            $byType[] = [
                'value' => $value,
                'label' => $definition['label'],
                'icon'  => $definition['icon'],
                'color' => $definition['color'],
                'total' => $count,
                'retired' => false,
            ];

            $total += $count;
        }

        foreach ($counts as $value => $count) {
            $byType[] = [
                'value'   => (string) $value,
                'label'   => TaxonomyService::label(self::EVENT_TAXONOMY, (string) $value),
                'icon'    => 'link',
                'color'   => '#64748B',
                'total'   => $count,
                'retired' => true,
            ];

            $total += $count;
        }

        return $window + ['total' => $total, 'by_type' => $byType];
    }

    /**
     * One row per day in the window, zero-filled.
     *
     * Zero-filling is not cosmetic: a chart drawn straight from GROUP BY
     * output joins Monday to Friday with a straight line and hides the three
     * days of nothing in between, which is the shape a creator most needs to
     * see.
     *
     * Profile views ride along from `creator_profile_views` because "what
     * happened on my profile" is one question, and the answer split across two
     * API calls gets rendered as two charts that nobody compares.
     *
     * Each day's `by_type` sums to exactly that day's `events`, retired event
     * types included — the same guarantee totals() makes, because both appear
     * on one screen and a stacked chart that stops short of its own headline
     * number is read as a bug in the dashboard.
     *
     * @return list<array{date:string,views:int,events:int,by_type:array<string,int>}>
     */
    public static function series(int $creatorId, ?string $from = null, ?string $to = null): array
    {
        $window   = self::window($from, $to);
        $bindings = ['c' => $creatorId, 'from' => $window['from'], 'to' => $window['to']];

        $rows = Database::select(
            'SELECT `occurred_on`, `event_type`, COUNT(*) AS `total`
               FROM `creator_engagement_events`
              WHERE `creator_id` = :c AND `occurred_on` BETWEEN :from AND :to
              GROUP BY `occurred_on`, `event_type`',
            $bindings
        );

        $blank = [];

        foreach (array_keys(self::catalogue()) as $value) {
            $blank[$value] = 0;
        }

        // An event type whose term has since been retired gets a slot too,
        // appended after the live catalogue exactly as totals() appends its
        // retired entries. It used to be counted in the day's `events` total
        // and dropped from `by_type`, which left a stacked chart that could
        // never reach the headline number printed above it — and had the two
        // aggregates in one dashboard() response disagreeing about the same
        // rows. The set is collected from the whole window before any day is
        // built so that every day carries the same keys: a legend that gains
        // and loses series as you scroll the axis is worse than an extra zero.
        foreach ($rows as $row) {
            $type = (string) $row['event_type'];

            if (!array_key_exists($type, $blank)) {
                $blank[$type] = 0;
            }
        }

        $days = [];

        for ($cursor = $window['from']; $cursor <= $window['to']; $cursor = date('Y-m-d', strtotime($cursor . ' +1 day'))) {
            $days[$cursor] = ['date' => $cursor, 'views' => 0, 'events' => 0, 'by_type' => $blank];
        }

        foreach ($rows as $row) {
            $day = (string) $row['occurred_on'];

            if (!isset($days[$day])) {
                continue;
            }

            $type  = (string) $row['event_type'];
            $count = (int) $row['total'];

            $days[$day]['events']          += $count;
            $days[$day]['by_type'][$type]  += $count;
        }

        foreach (Database::select(
            'SELECT `viewed_on`, COUNT(*) AS `total`
               FROM `creator_profile_views`
              WHERE `creator_id` = :c AND `viewed_on` BETWEEN :from AND :to
              GROUP BY `viewed_on`',
            $bindings
        ) as $row) {
            $day = (string) $row['viewed_on'];

            if (isset($days[$day])) {
                $days[$day]['views'] = (int) $row['total'];
            }
        }

        return array_values($days);
    }

    /**
     * Where the shares went, or which network was clicked — the breakdown of
     * one event type by its channel, labelled from the taxonomy that event
     * declares.
     *
     * ROWS WITH NO CHANNEL ARE COUNTED, in a trailing "Unspecified" bucket.
     * They are not an edge case: the operating system share sheet is the most
     * common way a profile gets shared and it tells the caller nothing about
     * where the link went, so `channel` is legitimately null for a large share
     * of this table. The query used to carry `AND channel IS NOT NULL`, which
     * hid those rows here while totals() went on counting them — three shares
     * above a breakdown that added up to one. totals() takes care to keep a
     * retired event type in the sum for exactly this reason; dropping the
     * channel-less shares was the same mistake one panel to the left.
     *
     * The bucket's `value` is null rather than a made-up term, because that is
     * precisely what is in the column and because any string we invented could
     * one day collide with a real term an operator adds.
     *
     * @return list<array<string,mixed>>
     */
    public static function channelBreakdown(
        int $creatorId,
        string $eventType,
        ?string $from = null,
        ?string $to = null
    ): array {
        $definition = self::definition($eventType);
        $taxonomy   = $definition['channel_taxonomy'];

        if ($taxonomy === null) {
            return [];
        }

        $window = self::window($from, $to);

        $terms = [];

        foreach (TaxonomyService::terms($taxonomy) as $term) {
            $terms[(string) $term['value']] = $term;
        }

        $out         = [];
        $unspecified = 0;

        foreach (Database::select(
            'SELECT `channel`, COUNT(*) AS `total`
               FROM `creator_engagement_events`
              WHERE `creator_id` = :c AND `event_type` = :e
                AND `occurred_on` BETWEEN :from AND :to
              GROUP BY `channel`
              ORDER BY `total` DESC, `channel`',
            ['c' => $creatorId, 'e' => $eventType, 'from' => $window['from'], 'to' => $window['to']]
        ) as $row) {
            $value = $row['channel'] === null ? '' : (string) $row['channel'];

            // GROUP BY collapses every NULL into one row, so this normally
            // runs once. The empty-string test is belt and braces:
            // validateChannel() turns '' into NULL on the way in, but this
            // table predates that guarantee by a migration.
            if ($value === '') {
                $unspecified += (int) $row['total'];

                continue;
            }

            $term = $terms[$value] ?? null;

            $out[] = [
                'value' => $value,
                'label' => $term !== null
                    ? (string) $term['label']
                    : TaxonomyService::label($taxonomy, $value),
                'icon'  => $term !== null ? (string) ($term['icon'] ?? 'link') : 'link',
                'color' => $term !== null ? (string) ($term['color'] ?? '#64748B') : '#64748B',
                'total' => (int) $row['total'],
            ];
        }

        // Appended last rather than sorted in among the named channels: it is
        // the one bar a creator can do nothing about, so it belongs at the end
        // of the legend, and omitted entirely when it is zero so the common
        // case reads exactly as it did before.
        if ($unspecified > 0) {
            $out[] = [
                'value' => null,
                'label' => 'Unspecified',
                'icon'  => 'link',
                'color' => '#94A3B8',
                'total' => $unspecified,
            ];
        }

        return $out;
    }

    /**
     * Which items of a creator's own get engaged with — the read that
     * `idx_cee_target` exists for.
     *
     * The join carries `creator_id` on both sides, so a row claiming somebody
     * else's portfolio item cannot appear here.
     *
     * That is NOT on its own a reason for record() to skip validating the
     * target, and this paragraph used to say it was. The join hides a forged
     * row from this report while leaving it counted in totals(), which is the
     * reconciliation failure — a per-item breakdown that does not add up to
     * the number printed above it. record() validates ownership up front
     * (assertTargetBelongs) precisely so the two agree; the join here is the
     * second line of defence, not the first.
     *
     * @return list<array<string,mixed>>
     */
    public static function topTargets(
        int $creatorId,
        string $eventType,
        int $limit = 10,
        ?string $from = null,
        ?string $to = null
    ): array {
        $definition = self::definition($eventType);
        $table      = $definition['target_table'];

        if ($table === null) {
            return [];
        }

        $window   = self::window($from, $to);
        $limit    = max(1, min(50, $limit));
        $bindings = ['c' => $creatorId, 'e' => $eventType, 'from' => $window['from'], 'to' => $window['to']];

        // An explicit query per table rather than an interpolated table name.
        // The value comes from operator-typed taxonomy metadata; a match() is
        // the difference between "the operator chooses which report runs" and
        // "the operator writes the FROM clause".
        $sql = match ($table) {
            // LEFT JOIN, not INNER, and the deletion test is a label rather
            // than a filter.
            //
            // record() refuses a target that is already gone, so the only way
            // to reach a missing row here is for the creator to delete an item
            // AFTER it was downloaded — which is ordinary behaviour. An INNER
            // JOIN dropped those rows from this breakdown while totals() went
            // on counting them, so the per-item list stopped adding up to the
            // number printed directly above it. Ownership is still enforced:
            // `t.creator_id = e.creator_id` stays in the ON clause, so another
            // creator's row can never resolve to a label.
            'creator_portfolio' => 'SELECT e.`target_id` AS `id`, COUNT(*) AS `total`,
                        COALESCE(t.`title`, "Removed item") AS `label`,
                        t.`media_kind` AS `kind`, t.`thumbnail_url` AS `thumbnail`,
                        (t.`id` IS NULL) AS `is_missing`
                   FROM `creator_engagement_events` e
                   LEFT JOIN `creator_portfolio` t
                          ON t.`id` = e.`target_id` AND t.`creator_id` = e.`creator_id`
                         AND t.`deleted_at` IS NULL
                  WHERE e.`creator_id` = :c AND e.`event_type` = :e
                    AND e.`occurred_on` BETWEEN :from AND :to
                  GROUP BY e.`target_id`, t.`id`, t.`title`, t.`media_kind`, t.`thumbnail_url`
                  ORDER BY `total` DESC, `id`
                  LIMIT ' . $limit,

            'creator_social_accounts' => 'SELECT e.`target_id` AS `id`, COUNT(*) AS `total`,
                        COALESCE(NULLIF(t.`label`, ""), NULLIF(t.`handle`, ""), t.`platform`, "Removed account") AS `label`,
                        t.`platform` AS `kind`, NULL AS `thumbnail`,
                        (t.`id` IS NULL) AS `is_missing`
                   FROM `creator_engagement_events` e
                   LEFT JOIN `creator_social_accounts` t
                          ON t.`id` = e.`target_id` AND t.`creator_id` = e.`creator_id`
                  WHERE e.`creator_id` = :c AND e.`event_type` = :e
                    AND e.`occurred_on` BETWEEN :from AND :to
                  GROUP BY e.`target_id`, t.`id`, t.`label`, t.`handle`, t.`platform`
                  ORDER BY `total` DESC, `id`
                  LIMIT ' . $limit,

            // An operator has pointed an event at a table this service has no
            // report for. Returning nothing is the honest answer; guessing at
            // a title column would either fail or invent one.
            default => null,
        };

        if ($sql === null) {
            return [];
        }

        $out = [];

        foreach (Database::select($sql, $bindings) as $row) {
            $out[] = [
                'id'        => (int) $row['id'],
                'total'     => (int) $row['total'],
                'label'     => (string) ($row['label'] ?? ''),
                'kind'      => (string) ($row['kind'] ?? ''),
                'thumbnail' => $row['thumbnail'] ?? null,
                // The item was deleted after these events were recorded. The
                // client should render it greyed rather than linking to a page
                // that no longer exists — and, more importantly, the row is
                // here at all so this list still sums to the headline total.
                'is_missing' => (bool) ($row['is_missing'] ?? false),
            ];
        }

        return $out;
    }

    /**
     * Profile views split by where they came from.
     *
     * This is the read that makes migration 039's ENUM-to-taxonomy swap
     * visible: `public` and `qr` views were unrecordable before it and
     * unreportable until here.
     *
     * @return array{total:int,by_source:list<array<string,mixed>>}
     */
    public static function viewsBySource(int $creatorId, ?string $from = null, ?string $to = null): array
    {
        $window = self::window($from, $to);

        $counts = [];

        foreach (Database::select(
            'SELECT `source`, COUNT(*) AS `total`
               FROM `creator_profile_views`
              WHERE `creator_id` = :c AND `viewed_on` BETWEEN :from AND :to
              GROUP BY `source`',
            ['c' => $creatorId, 'from' => $window['from'], 'to' => $window['to']]
        ) as $row) {
            $counts[(string) $row['source']] = (int) $row['total'];
        }

        $bySource = [];
        $total    = 0;

        foreach (TaxonomyService::terms(self::VIEW_SOURCE_TAXONOMY) as $term) {
            $value = (string) $term['value'];
            $count = $counts[$value] ?? 0;
            unset($counts[$value]);

            $bySource[] = [
                'value' => $value,
                'label' => (string) $term['label'],
                'icon'  => (string) ($term['icon'] ?? 'arrow-right'),
                'color' => (string) ($term['color'] ?? '#64748B'),
                'total' => $count,
            ];

            $total += $count;
        }

        // Same rule as totals(): a source whose term was retired still counted
        // as a view when it happened, so it stays in the sum.
        foreach ($counts as $value => $count) {
            $bySource[] = [
                'value' => (string) $value,
                'label' => TaxonomyService::label(self::VIEW_SOURCE_TAXONOMY, (string) $value),
                'icon'  => 'arrow-right',
                'color' => '#64748B',
                'total' => $count,
            ];

            $total += $count;
        }

        return ['total' => $total, 'by_source' => $bySource];
    }

