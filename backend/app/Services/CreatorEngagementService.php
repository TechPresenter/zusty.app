<?php

declare(strict_types=1);

namespace Zuste\Services;

use Zuste\Core\Config;
use Zuste\Core\Database;
use Zuste\Core\HttpException;
use Zuste\Core\QrCode;

/**
 * Public profile visibility, sharing, and engagement events.
 *
 * Migration 039 shipped three things and wired none of them: the `is_public`
 * flag on `creators`, the `creator_engagement_events` table, and the
 * `profile_view_source` taxonomy that replaced an ENUM which could not express
 * a QR scan. This service is what makes those columns mean something.
 *
 * Three responsibilities, deliberately in one file because they are one
 * feature — a creator's public presence:
 *
 *   1. RECORDING. Shares, QR downloads, portfolio downloads and social link
 *      clicks land in one table, validated against the `engagement_event`
 *      taxonomy so the catalogue is an operator's list rather than a switch
 *      statement here.
 *   2. AGGREGATING. Totals and a daily series per creator, answered straight
 *      from `idx_cee_rollup` with no nightly rollup to drift out of step.
 *   3. VISIBILITY. `is_public` is the creator's own switch, distinct from
 *      `status`, which is the platform's verdict. Live means all three of
 *      status = 'approved', is_public = 1 and deleted_at IS NULL — and that
 *      clause lives here, once, in publicClause().
 *
 * The QR code is generated by Zuste\Core\QrCode, which already existed for the
 * two-factor enrolment screen. Nothing about a profile QR is different from a
 * TOTP QR except the string inside it, so a second encoder would only be a
 * second place for a mask-penalty bug to hide.
 */
final class CreatorEngagementService
{
    /** Countable actions on a profile. Its terms name their own vocabularies. */
    public const EVENT_TAXONOMY = 'engagement_event';

    /** Where a profile view came from — the ENUM migration 039 dissolved. */
    public const VIEW_SOURCE_TAXONOMY = 'profile_view_source';

    /** Destinations a profile can be shared to; drives the share sheet. */
    public const SHARE_CHANNEL_TAXONOMY = 'share_channel';

    /**
     * The default reporting window, and the hard ceiling on one.
     *
     * The ceiling is not politeness. `series()` zero-fills every day in the
     * range in PHP, so an unbounded `from` handed in from a query string would
     * build an array with one entry per day since the epoch before it ever
     * touched the database.
     */
    private const DEFAULT_WINDOW_DAYS = 30;
    private const MAX_WINDOW_DAYS     = 366;

    /**
     * The public profile path, with `{handle}` substituted.
     *
     * This matches the pattern SitemapService publishes for creators. The two
     * MUST agree: a share link that resolves to a URL the sitemap never
     * declared splits the page's link equity across two addresses and hands
     * crawlers a canonical they have never seen. Overridable from settings for
     * the day the web front-end moves the route, because a mismatch between a
     * printed QR code and the live site is not something a release can fix.
     */
    private const DEFAULT_PROFILE_PATH = '/creators/{handle}';

    /**
     * The forms one QR code can be handed back in.
     *
     * Public so a client, and the proof, can name them without copying the
     * strings. `matrix` is the raw modules (~1.7 KB), `svg` a ready-to-render
     * image (~24 KB at module size 6), `data_uri` that same SVG base64'd for
     * an <img src> (~33 KB). They describe ONE code — asking for all three
     * ships it three times.
     */
    public const QR_REPRESENTATIONS = ['matrix', 'svg', 'data_uri'];

    /**
     * What a share payload returns when the caller does not choose.
     *
     * One renderable form, not three. See sharePayload() for the measurements
     * behind that.
     */
    private const DEFAULT_QR_REPRESENTATIONS = ['svg'];

    /**
     * Target tables an event may point into, with the columns that describe a
     * row for the "most downloaded item" report.
     *
     * A whitelist rather than a read of the term's `metadata.target_table`,
     * even though that is where the value comes from. Taxonomy metadata is
     * typed by an operator in the admin panel; interpolating it into a FROM
     * clause would turn the taxonomy editor into an SQL console. The metadata
     * still SELECTS which entry is used — it just cannot invent one.
     *
     * @var array<string,string>
     */
    private const TARGET_TABLES = [
        'creator_portfolio'       => 'portfolio item',
        'creator_social_accounts' => 'social account',
    ];

    /**
     * Per-request memo of the resolved catalogue and of the channel
     * vocabularies it names.
     *
     * TaxonomyService caches the whole bundle, but every call through it runs
     * version() first — four indexed subqueries — to build the cache key, and
     * on a host without APCu (this one: `php -m` has no apcu, so Cache falls
     * back to its database driver) the cache read is itself another statement.
     * Without this memo record() would pay the catalogue and the channel map
     * again on every call rather than once per process.
     *
     * READ THE COST HONESTLY. This memo is per PROCESS, and under PHP-FPM or
     * `php -S` a process is one request, so the cold number is what a real
     * request pays.
     *
     * Measured on this host (no APCu, so Cache uses its database driver),
     * three consecutive fresh processes:
     *
     *     record() cold = 6 statements, warm = 2
     *     cold = 7 when the taxonomy bundle has just been flushed
     *
     * The exact figure is state-dependent — it moves with what the process has
     * already touched — so treat 6-8 as the range and 2 as the steady state,
     * not any single number as gospel.
     *
     * An earlier version of this file advertised "one INSERT", which was only
     * ever true of the second and later calls inside one process. Stating that
     * as the steady state led to a real design mistake: it was used to argue
     * that record() could not afford to validate target ownership. It can, it
     * does, and the reconciliation that validation buys is worth one statement
     * (see record() and topTargets()).
     *
     * An operator editing a term in the admin panel is a different request and
     * sees the change immediately; a long-running CLI job would hold the
     * catalogue it started with, which for a rollup job is what you want
     * anyway — the vocabulary must not shift mid-run.
     *
     * @var array<string,array<string,mixed>>|null
     */
    private static ?array $catalogue = null;

    /** @var array<string,array<string,string>> Channel taxonomy key => value => label. */
    private static array $channelMaps = [];

    // =================================================================
    // The catalogue
    // =================================================================

    /**
     * Every event type an operator has published, with its rules resolved.
     *
     * `channel_taxonomy` and `target_table` come from the term's metadata, so
     * adding "package viewed" or "contact revealed" is a row in the admin
     * panel and not a release — which is the whole reason migration 039 put
     * them in the term instead of in this file.
     *
     * @return array<string,array<string,mixed>> Keyed by event value, in the
     *                                           operator's chosen order.
     */
    public static function catalogue(): array
    {
        if (self::$catalogue !== null) {
            return self::$catalogue;
        }

        $out = [];

        foreach (TaxonomyService::terms(self::EVENT_TAXONOMY) as $term) {
            $meta = is_array($term['metadata'] ?? null) ? $term['metadata'] : [];

            $channelTaxonomy = $meta['channel_taxonomy'] ?? null;
            $targetTable     = $meta['target_table'] ?? null;

            $out[(string) $term['value']] = [
                'value'       => (string) $term['value'],
                'label'       => (string) $term['label'],
                'description' => (string) ($term['description'] ?? ''),
                // 'link' rather than a prettier name because View::icon()
                // renders NOTHING for a name it does not know, and does it
                // silently. A fallback that is not in the map is not a
                // fallback — it is an empty cell on the admin screen.
                'icon'        => (string) ($term['icon'] ?? 'link'),
                // TaxonomyService renames `color_hex` to `color` on the way
                // out. Reading the column name here would give every event the
                // fallback grey, which is the bug CreatorBadgeService already
                // had to fix once.
                'color'       => (string) ($term['color'] ?? '#64748B'),

                // Empty string is what an operator leaves behind when they
                // clear the field, and JSON null is what the seed wrote.
                // Both mean "this event has no channel", so both normalise to
                // null rather than to a taxonomy key of ''.
                'channel_taxonomy' => is_string($channelTaxonomy) && $channelTaxonomy !== ''
                    ? $channelTaxonomy
                    : null,

                'target_table' => is_string($targetTable) && $targetTable !== ''
                    ? $targetTable
                    : null,
            ];
        }

        return self::$catalogue = $out;
    }

    /**
     * Drop the memo.
     *
     * Only a caller that has just edited the taxonomy in the same process
     * needs this — the admin panel's term editor, and the proof script.
     */
    public static function flushCatalogue(): void
    {
        self::$catalogue   = null;
        self::$channelMaps = [];
    }

    /**
     * One channel vocabulary as value => label, memoised.
     *
     * @return array<string,string>
     */
    private static function channelMap(string $taxonomy): array
    {
        return self::$channelMaps[$taxonomy] ??= TaxonomyService::map($taxonomy);
    }

    /**
     * Resolve an event type or refuse it.
     *
     * @return array<string,mixed>
     */
    private static function definition(string $eventType): array
    {
        $catalogue = self::catalogue();

        if (!isset($catalogue[$eventType])) {
            throw HttpException::unprocessable("Unknown engagement event: {$eventType}");
        }

        return $catalogue[$eventType];
    }

    /**
     * The channel options for one event type, ready for a share sheet.
     *
     * Empty for an event that takes no channel — a portfolio download did not
     * happen "on WhatsApp".
     *
     * @return list<array<string,mixed>>
     */
    public static function channelsFor(string $eventType): array
    {
        $taxonomy = self::definition($eventType)['channel_taxonomy'];

        return $taxonomy === null ? [] : TaxonomyService::terms($taxonomy);
    }

    // =================================================================
    // Recording
    // =================================================================

    /**
     * Record one engagement event.
     *
     * WHY THIS READS THE CREATOR ROW FIRST. An earlier version of this method
     * did not, on the stated grounds that a lookup "would be the second query
     * this method exists to avoid". That reasoning rested on a measurement
     * that was never true in production: see the note on $catalogue — the cold
     * cost was already eight statements, and the caller over HTTP then paid a
     * ninth for its own canView() gate. Trading a defensible invariant for a
     * saving that did not exist is the worst kind of optimisation, so the gate
     * moved IN HERE and the caller's duplicate read went away. Net statement
     * count over HTTP is unchanged; three defects are gone.
     *
     * The single row this reads answers all three:
     *
     *   1. EXISTENCE. `deleted_at IS NULL` is part of the lookup, so a
     *      soft-deleted profile refuses the write instead of accumulating rows
     *      no report can ever attribute. Relying on `fk_cee_creator` could not
     *      do this — the foreign key still holds for a soft-deleted row — and
     *      it did not even cover the whole input domain: a negative id fails
     *      the unsigned column's range check before it reaches the constraint,
     *      which surfaced as a 500 rather than a 404.
     *   2. SELF-GENERATED ACTIVITY. A creator acting on their own profile is
     *      not engagement. CreatorService::recordView() has always refused to
     *      count a creator viewing themselves; without the same rule here the
     *      owner could POST unlimited shares and downloads at themselves, and
     *      the two halves of the same dashboard would disagree about whether
     *      self-activity counts.
     *   3. VISIBILITY. Anyone who may not see the profile may not record
     *      against it. This lives here rather than in the controller so that a
     *      future caller — admin panel, cron, importer — cannot skip it.
     *
     * The target is verified to belong to this creator for the same
     * reconciliation reason channelBreakdown() grew an "Unspecified" bucket: a
     * forged target_id counted towards the event's headline total while
     * topTargets() (which joins on creator_id) could never show it, so the
     * per-item panel silently summed to less than the number above it.
     *
     * @param  array<string,mixed> $context channel, target_id, actor_id.
     * @return int The new event id, or 0 when the event was deliberately not
     *             counted because the actor owns the profile.
     */
    public static function record(int $creatorId, string $eventType, array $context = []): int
    {
        $definition = self::definition($eventType);

        // Shape validation first: it is answered from the memoised taxonomy
        // and touches no table, so a malformed payload never costs a read.
        $channel  = self::validateChannel($definition, $context['channel'] ?? null);
        $targetId = self::normaliseTarget($definition, $context['target_id'] ?? null);

        $actorId = isset($context['actor_id']) && (int) $context['actor_id'] > 0
            ? (int) $context['actor_id']
            : null;

        $creator = Database::selectOne(
            'SELECT `id`, `user_id`, `status`, `is_public` FROM `creators`
              WHERE `id` = :id AND `deleted_at` IS NULL',
            ['id' => $creatorId]
        );

        if ($creator === null) {
            throw HttpException::notFound('Creator not found.');
        }

        // Owner first, exactly as canView() orders it: a creator may reach
        // their own profile while it is switched off, and what they do there
        // is still not engagement. Silently uncounted rather than refused —
        // the share sheet on a creator's own preview screen must work, it just
        // must not move the numbers. recordView() takes the same line.
        if ($actorId !== null && (int) $creator['user_id'] === $actorId) {
            return 0;
        }

        // 404 and not 403, for the reason assertViewable() spells out: a 403
        // would confirm that a private handle exists.
        if ($creator['status'] !== 'approved' || (int) $creator['is_public'] !== 1) {
            throw HttpException::notFound('Creator not found.');
        }

        if ($targetId !== null) {
            self::assertTargetBelongs($definition, $creatorId, $targetId);
        }

        try {
            return Database::insert('creator_engagement_events', [
                'creator_id'  => $creatorId,
                'event_type'  => $eventType,
                'channel'     => $channel,
                'target_id'   => $targetId,
                'actor_id'    => $actorId,
                // Denormalised so a daily rollup is a range scan on
                // idx_cee_rollup rather than DATE(created_at) on every row,
                // which no index can serve.
                'occurred_on' => date('Y-m-d'),
                'created_at'  => date('Y-m-d H:i:s'),
            ]);
        } catch (\PDOException $e) {
            // The gate above has already established that the creator exists,
            // so this is now a race net rather than the primary path: a
            // profile hard-deleted between the read and the write. Still
            // translated, because a 404 is the truthful answer to it.
            //
            // Only the creator constraint is turned into a 404. A violation on
            // fk_cee_actor means an authenticated session is pointing at a
            // user row that no longer exists, which is a real fault and must
            // not be disguised as "creator not found".
            if (str_contains($e->getMessage(), 'fk_cee_creator')) {
                throw HttpException::notFound('Creator not found.');
            }

            throw $e;
        }
    }

    /**
     * A channel is legal only if the event type declares a vocabulary for it
     * and the value is a live term in that vocabulary.
     *
     * Both failures throw rather than nulling the value. Silently dropping an
     * unrecognised channel is exactly what the old `recordView()` whitelist
     * did to `source`: the write appeared to succeed, the dashboard showed
     * nothing, and nobody could tell whether the client was wrong or the data
     * was empty.
     *
     * @param array<string,mixed> $definition
     */
    private static function validateChannel(array $definition, mixed $channel): ?string
    {
        $channel = is_string($channel) ? trim($channel) : '';

        if ($channel === '') {
            return null;
        }

        $taxonomy = $definition['channel_taxonomy'];

        if ($taxonomy === null) {
            throw HttpException::unprocessable(
                "A \"{$definition['label']}\" event does not have a channel."
            );
        }

        if (!array_key_exists($channel, self::channelMap($taxonomy))) {
            throw HttpException::unprocessable(
                "Unknown {$taxonomy} channel: {$channel}"
            );
        }

        return $channel;
    }

    /**
     * A target is required exactly when the event type names a table for it.
     *
     * "Portfolio item downloaded" with no item is an unanswerable row — it
     * inflates the total and can never appear in the per-item report — so it
     * is refused at the door rather than stored and puzzled over later.
     *
     * Shape only; ownership is a read and belongs after the creator gate.
     *
     * @param array<string,mixed> $definition
     */
    private static function normaliseTarget(array $definition, mixed $targetId): ?int
    {
        $targetId = $targetId === null || $targetId === '' ? 0 : (int) $targetId;
        $table    = $definition['target_table'];

        if ($table === null) {
            if ($targetId > 0) {
                throw HttpException::unprocessable(
                    "A \"{$definition['label']}\" event applies to the whole profile, not to one item."
                );
            }

            return null;
        }

        if ($targetId <= 0) {
            $noun = self::TARGET_TABLES[$table] ?? 'item';

            throw HttpException::unprocessable(
                "A \"{$definition['label']}\" event must name the {$noun} it refers to."
            );
        }

        return $targetId;
    }

    /**
     * The named target must be this creator's own.
     *
     * This endpoint is open to anonymous callers, so target_id is attacker
     * controlled. Storing a row that names somebody else's portfolio item adds
     * one to `portfolio_download` in totals() and in the daily series, while
     * topTargets() — which joins on id AND creator_id — can never show it. The
     * creator then reads "12 downloads" above a list that adds up to 9 and has
     * no way to find the missing three. Refusing the row is the only answer
     * that keeps the two panels talking about the same events.
     *
     * The SQL is chosen by match() over the whitelist rather than interpolated
     * from the term's metadata, for the reason TARGET_TABLES documents: the
     * operator picks which check runs, they do not write it.
     *
     * @param array<string,mixed> $definition
     */
    private static function assertTargetBelongs(array $definition, int $creatorId, int $targetId): void
    {
        $table = (string) $definition['target_table'];

        $sql = match ($table) {
            'creator_portfolio' => 'SELECT COUNT(*) FROM `creator_portfolio`
                                     WHERE `id` = :t AND `creator_id` = :c AND `deleted_at` IS NULL',

            'creator_social_accounts' => 'SELECT COUNT(*) FROM `creator_social_accounts`
                                           WHERE `id` = :t AND `creator_id` = :c',

            // An operator has pointed an event at a table this service has no
            // report for. There is nothing to reconcile against, so there is
            // nothing to enforce; topTargets() already returns [] for it.
            default => null,
        };

        if ($sql === null) {
            return;
        }

        if ((int) Database::scalar($sql, ['t' => $targetId, 'c' => $creatorId]) === 0) {
            $noun = self::TARGET_TABLES[$table] ?? 'item';

            throw HttpException::unprocessable(
                "That {$noun} does not belong to this profile."
            );
        }
    }

