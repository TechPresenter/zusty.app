    /**
     * The public URL for a handle.
     *
     * Built from `creators`.`handle`, which is UNIQUE and NOT NULL, so there
     * is no second identifier to keep in step and no stored slug that can
     * disagree with the name on the profile.
     *
     * The base comes from SitemapService::baseUrl() on purpose — one canonical
     * base for the whole site, read from configuration rather than from the
     * request, so a forged Host header cannot end up printed on a QR code.
     */
    public static function shareUrl(string $handle): string
    {
        $path = trim(Config::settingString('seo', 'creator_profile_path', self::DEFAULT_PROFILE_PATH));

        // The setting is a PATH, and anything that looks like a whole address
        // is rejected outright rather than patched up. An operator who typed
        // "https://zusty.app/{handle}" into the box used to get
        // "https://zusty.app/https://zusty.app/aanya.kapoor" — a dead link,
        // and one that goes on printed QR codes and into share sheets, where
        // it cannot be fixed by a release. Falling back to the known-good
        // default is recoverable; a mangled URL in the wild is not.
        //
        // The leading "//" test covers the protocol-relative form, which
        // survives the "://" test and produces the same unreachable address.
        $isAbsolute = str_contains($path, '://') || str_starts_with($path, '//');

        if ($path === '' || !str_contains($path, '{handle}') || $isAbsolute) {
            $path = self::DEFAULT_PROFILE_PATH;
        }

        if ($path[0] !== '/') {
            $path = '/' . $path;
        }

        // Handles are validated as [a-z0-9._] elsewhere, but this string is
        // about to be encoded into a QR that gets printed. Encoding costs
        // nothing and removes the whole class of question.
        return SitemapService::baseUrl() . str_replace('{handle}', rawurlencode($handle), $path);
    }

    /**
     * Everything a client needs to render a share sheet and a QR code.
     *
     * Nothing here is stored. A `qr_image_url` column would be a cached render
     * of a string this rebuilds from scratch, and it would go stale the moment
     * a creator changed their handle.
     *
     * WHAT THE QR COSTS, MEASURED, because the last set of numbers written
     * here were a guess: QrCode::encode() plus an SVG render averages ~10 ms,
     * and serialising all three representations of one code — `svg` (~24 KB),
     * `data_uri` (a base64 copy of that same SVG, ~33 KB) and `matrix`
     * (~1.7 KB) — took the JSON body to ~52 KB. On an anonymous, uncacheable
     * GET that is an amplification lever pointed at ourselves, and no client
     * has ever needed more than one of the three. So they are opt-in: the
     * default is the single form a browser can render, and a native app that
     * wants the raw modules, or a caller that wants no QR at all, asks.
     *
     * @param  int|null           $viewerUserId    The signed-in user, for the visibility gate.
     * @param  list<string>       $representations Any of QR_REPRESENTATIONS; [] omits the QR entirely.
     * @return array<string,mixed>
     */
    public static function sharePayload(
        int $creatorId,
        ?int $viewerUserId = null,
        int $moduleSize = 6,
        array $representations = self::DEFAULT_QR_REPRESENTATIONS
    ): array {
        $creator = self::creatorRow($creatorId);

        self::assertViewable($creator, $viewerUserId);

        $url = self::shareUrl((string) $creator['handle']);

        $appName = Config::settingString('general', 'app_name', 'Zusty');
        $title   = (string) $creator['display_name'];
        $tagline = trim((string) ($creator['headline'] ?? ''));

        return [
            'creator_id' => (int) $creator['id'],
            'handle'     => (string) $creator['handle'],
            'url'        => $url,
            'title'      => $title,
            // The text a share sheet pre-fills. Assembled here rather than in
            // each client so the wording is one string to change, not three.
            'text'       => $tagline !== ''
                ? sprintf('%s — %s on %s', $title, $tagline, $appName)
                : sprintf('%s on %s', $title, $appName),
            // encodeQr() and not qr(): a URL too long to encode must not turn
            // a creator's share sheet into an error page. The link, the title,
            // the pre-filled text and the destinations are all still useful
            // without a QR, so the field goes null and the sheet still opens.
            'qr'         => $representations === []
                ? null
                : self::encodeQr($url, $moduleSize, $representations),
            // The share sheet is drawn from the taxonomy, so an operator
            // adding a destination does not need an app release.
            'channels'   => TaxonomyService::terms(self::SHARE_CHANNEL_TAXONOMY),
            'is_live'    => self::isPubliclyVisible($creatorId),
        ];
    }

    /**
     * A QR code for any string, in the representations asked for.
     *
     * Encoded by Zuste\Core\QrCode — the encoder written for two-factor
     * enrolment, kept because a QR code generated by a third-party chart API
     * means posting the payload to that service, and the same objection that
     * applied to a TOTP secret applies to anything else we would rather not
     * hand over.
     *
     * `data_uri` exists because a client that cannot host an SVG can drop it
     * straight into an <img src>, and `matrix` because a native app draws its
     * own modules to match its theme. All three by default here, because a
     * caller reaching for this helper directly has asked for a QR and nothing
     * else; sharePayload() is the one with a body size to answer for and it
     * names what it wants.
     *
     * @param  list<string> $representations Any of QR_REPRESENTATIONS.
     * @return array<string,mixed> text, modules, and the requested forms.
     */
    public static function qr(
        string $text,
        int $moduleSize = 6,
        array $representations = self::QR_REPRESENTATIONS
    ): array {
        $qr = self::encodeQr($text, $moduleSize, $representations);

        // QrCode tops out at version 10, and above that capacity it throws
        // InvalidArgumentException — which escaped this method as a 500. It is
        // not reachable from a handle today (`creators`.`handle` is varchar(60)
        // and the longest live share URL is 49 bytes), but it becomes
        // reachable the moment an operator sets a long seo.creator_profile_path,
        // and "the encoder cannot fit this" is a 422, not a server fault.
        if ($qr === null) {
            throw HttpException::unprocessable(
                'That address is too long to encode as a QR code.'
            );
        }

        return $qr;
    }

    /**
     * Encode once, serialise only what was asked for; null when it will not fit.
     *
     * The SVG is built when either `svg` or `data_uri` is wanted, because the
     * data URI is just that string base64'd — rendering it twice would double
     * the only expensive part of the job.
     *
     * @param  list<string> $representations
     * @return array<string,mixed>|null
     */
    private static function encodeQr(string $text, int $moduleSize, array $representations): ?array
    {
        $moduleSize = max(1, min(20, $moduleSize));

        try {
            $matrix = QrCode::encode($text);
        } catch (\InvalidArgumentException) {
            return null;
        }

        $out = [
            'text'    => $text,
            'modules' => count($matrix),
        ];

        $wantsSvg     = in_array('svg', $representations, true);
        $wantsDataUri = in_array('data_uri', $representations, true);

        if ($wantsSvg || $wantsDataUri) {
            $svg = self::qrSvg($matrix, $moduleSize);

            if ($wantsSvg) {
                $out['svg'] = $svg;
            }

            if ($wantsDataUri) {
                $out['data_uri'] = 'data:image/svg+xml;base64,' . base64_encode($svg);
            }
        }

        if (in_array('matrix', $representations, true)) {
            $out['matrix'] = $matrix;
        }

        return $out;
    }

    /**
     * Turn a client's `qr=` parameter into a representation list.
     *
     * Unknown names are refused rather than dropped, for the reason
     * validateChannel() gives: a silently ignored parameter looks to the
     * client exactly like a server that does not have the data.
     *
     * @return list<string>
     */
    public static function qrRepresentations(string $requested): array
    {
        $requested = trim($requested);

        if ($requested === '') {
            return self::DEFAULT_QR_REPRESENTATIONS;
        }

        // The explicit opt-out, for a caller that wants the URL and the share
        // text and has no use for ten milliseconds of QR encoding.
        if (strtolower($requested) === 'none') {
            return [];
        }

        $out = [];

        foreach (explode(',', $requested) as $part) {
            $part = trim($part);

            if ($part === '') {
                continue;
            }

            if (!in_array($part, self::QR_REPRESENTATIONS, true)) {
                throw HttpException::unprocessable(
                    'Unknown QR representation: ' . $part
                    . '. Choose from ' . implode(', ', self::QR_REPRESENTATIONS) . ', or "none".'
                );
            }

            if (!in_array($part, $out, true)) {
                $out[] = $part;
            }
        }

        // A list that was not empty but yielded nothing — "," or " , , " —
        // means the client built the parameter badly. Returning [] here would
        // be indistinguishable from an explicit "none": the caller would get a
        // share sheet with no QR and nothing to tell them why, which is the
        // silent-drop this method's own rule above forbids.
        if ($out === []) {
            throw HttpException::unprocessable(
                'No QR representation was named. Choose from '
                . implode(', ', self::QR_REPRESENTATIONS) . ', or "none".'
            );
        }

        return $out;
    }

    /**
     * Render a QR matrix as SVG.
     *
     * The four-module quiet zone is required by the specification, not
     * decoration — scanners use it to find the code's edge, and a QR pasted
     * flush against dark page furniture stops reading without it.
     *
     * @param list<list<int>> $matrix
     */
    private static function qrSvg(array $matrix, int $moduleSize): string
    {
        $size  = count($matrix);
        $quiet = 4;
        $total = ($size + $quiet * 2) * $moduleSize;

        $rects = '';

        for ($y = 0; $y < $size; $y++) {
            for ($x = 0; $x < $size; $x++) {
                if ($matrix[$y][$x] !== 1) {
                    continue;
                }

                $rects .= sprintf(
                    '<rect x="%d" y="%d" width="%d" height="%d"/>',
                    ($x + $quiet) * $moduleSize,
                    ($y + $quiet) * $moduleSize,
                    $moduleSize,
                    $moduleSize
                );
            }
        }

        // The white background rectangle is load-bearing: an SVG with a
        // transparent background inverts on a dark theme and becomes
        // unscannable, since scanners expect dark modules on light.
        return sprintf(
            '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d" '
            . 'shape-rendering="crispEdges" role="img" aria-label="Creator profile QR code">'
            . '<rect width="%d" height="%d" fill="#ffffff"/><g fill="#000000">%s</g></svg>',
            $total,
            $total,
            $total,
            $total,
            $total,
            $total,
            $rects
        );
    }

