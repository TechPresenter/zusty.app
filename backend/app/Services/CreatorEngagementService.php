    /**
     * The one definition of "publicly visible", as an SQL fragment.
     *
     * Exposed so search, the profile lookup and the sitemap can all filter on
     * the same three columns without three hand-written copies that drift.
     * `idx_creators_public` (status, is_public, deleted_at) covers it exactly
     * in this order.
     */
    public static function publicClause(string $alias = 'c'): string
    {
        $prefix = $alias === '' ? '' : Database::quoteIdentifier($alias) . '.';

        return $prefix . '`status` = \'approved\' AND ' . $prefix . '`is_public` = 1 AND ' . $prefix . '`deleted_at` IS NULL';
    }

    /**
     * Is this profile visible to the public right now?
     *
     * All three conditions, every time. `status` alone was the old test and it
     * is why is_public has been inert since migration 039 ran.
     */
    public static function isPubliclyVisible(int $creatorId): bool
    {
        return (int) Database::scalar(
            'SELECT COUNT(*) FROM `creators` WHERE `id` = :id AND ' . self::publicClause(''),
            ['id' => $creatorId]
        ) > 0;
    }

    /**
     * The visibility state of one profile, with the reasons it is not live.
     *
     * The blockers are sentences, not codes, because the creator settings
     * screen has to explain "your profile is off" and "your profile is still
     * being reviewed" differently — the first is theirs to fix with the toggle
     * beside the message, the second is not.
     *
     * @return array<string,mixed>
     */
    public static function visibility(int $creatorId): array
    {
        $creator = self::creatorRow($creatorId);

        $isPublic = (bool) $creator['is_public'];
        $status   = (string) $creator['status'];
        $blockers = [];

        if ($status !== 'approved') {
            $blockers[] = $status === 'suspended' || $status === 'rejected'
                ? 'Your profile is not approved, so it cannot be shown publicly. Contact support for the next step.'
                : 'Your profile has not been approved yet, so it is not shown publicly.';
        }

        if (!$isPublic) {
            $blockers[] = 'You have switched your public profile off.';
        }

        return [
            'creator_id'    => (int) $creator['id'],
            'handle'        => (string) $creator['handle'],
            'is_public'     => $isPublic,
            'status'        => $status,
            'is_live'       => $isPublic && $status === 'approved',
            // Only the creator can clear this one, which is what the app needs
            // to know to decide whether the toggle does anything useful.
            'can_go_live'   => $status === 'approved',
            'blockers'      => $blockers,
            'share_url'     => self::shareUrl((string) $creator['handle']),
        ];
    }

    /**
     * Turn a public profile on or off.
     *
     * Deliberately independent of `status`: a creator taking their profile
     * down for a month must not land back in the review queue when they put it
     * up again, which is what would happen if this were a status change.
     *
     * A no-op change writes nothing and logs nothing — a settings screen that
     * saves on every render must not fill the audit trail with "changed public
     * profile from on to on".
     *
     * @param  array<string,mixed> $context actor_type, actor_id, actor_name.
     * @return array<string,mixed> The new visibility state.
     */
    public static function setVisibility(int $creatorId, bool $isPublic, array $context = []): array
    {
        $creator = self::creatorRow($creatorId);

        if ((bool) $creator['is_public'] === $isPublic) {
            return self::visibility($creatorId);
        }

        Database::update('creators', [
            'is_public'  => $isPublic ? 1 : 0,
            // Touched on purpose. `updated_at` is the sitemap's <lastmod>, and
            // a profile appearing or disappearing from the index is exactly
            // the kind of change a crawler should be told about.
            'updated_at' => date('Y-m-d H:i:s'),
        ], ['id' => $creatorId]);

        // `activity_logs`.`actor_type` is enum('admin','user','system','cron')
        // and has no 'creator'. A creator acting on their own profile IS a
        // user there — the creator is the SUBJECT of the row, not the actor
        // type. Passing 'creator' through would be an out-of-enum insert,
        // which under STRICT_TRANS_TABLES throws, and ActivityLogger swallows
        // its own failures so the audit row would simply never appear. The
        // proof script caught exactly that.
        $actorType = match ((string) ($context['actor_type'] ?? 'creator')) {
            'admin'  => 'admin',
            'cron'   => 'cron',
            'system' => 'system',
            default  => 'user',
        };

        ActivityLogger::log(
            'creator.visibility_changed',
            'creator',
            $creatorId,
            $isPublic ? 'Public profile switched on.' : 'Public profile switched off.',
            ['is_public' => ['from' => (bool) $creator['is_public'], 'to' => $isPublic]],
            $actorType,
            isset($context['actor_id']) ? (int) $context['actor_id'] : null,
            isset($context['actor_name']) ? (string) $context['actor_name'] : null
        );

        return self::visibility($creatorId);
    }

    /**
     * The default a brand-new profile is created with.
     *
     * Read from `creator.default_profile_visibility`, which already existed as
     * a setting and had nothing reading it. An operator running a marketplace
     * that reviews every profile by hand wants new creators private until they
     * choose to appear.
     */
    public static function defaultIsPublic(): bool
    {
        return Config::settingString('creator', 'default_profile_visibility', 'public') !== 'private';
    }

    /**
     * May this viewer see this profile?
     *
     * The owner always can — that is the whole of "preview": their own profile
     * rendered exactly as the public would see it, with the gate skipped
     * rather than a second rendering path to keep in step.
     *
     * record() applies the same three tests against the row it already has to
     * fetch, so a caller recording an event does not need to ask first. This
     * stays for callers that need the answer WITHOUT writing anything — a
     * client deciding whether to draw the share button, for one. If the rule
     * ever changes it has to change in both, which is why both spell it out in
     * the same order: owner, then approved, then public.
     */
    public static function canView(int $creatorId, ?int $viewerUserId): bool
    {
        $creator = Database::selectOne(
            'SELECT `id`, `user_id`, `status`, `is_public` FROM `creators`
              WHERE `id` = :id AND `deleted_at` IS NULL',
            ['id' => $creatorId]
        );

        if ($creator === null) {
            return false;
        }

        if ($viewerUserId !== null && (int) $creator['user_id'] === $viewerUserId) {
            return true;
        }

        return $creator['status'] === 'approved' && (int) $creator['is_public'] === 1;
    }

    /**
     * Refuse a viewer who may not see this profile.
     *
     * 404, never 403. A 403 confirms that the handle exists and that someone
     * has switched it off, which is precisely the fact a creator who went
     * private is trying not to publish.
     *
     * @param array<string,mixed> $creator A row from creatorRow().
     */
    private static function assertViewable(array $creator, ?int $viewerUserId): void
    {
        if ($viewerUserId !== null && (int) $creator['user_id'] === $viewerUserId) {
            return;
        }

        if ($creator['status'] !== 'approved' || (int) $creator['is_public'] !== 1) {
            throw HttpException::notFound('Creator not found.');
        }
    }

    /**
     * The owner's preview of their own public profile.
     *
     * Built by calling CreatorService::profile() with the owner as the viewer,
     * so the preview is the real payload rather than a lookalike assembled
     * here — a second builder would drift from the real one within a release
     * and the preview would start lying.
     *
     * @return array<string,mixed>
     */
    public static function preview(int $creatorId, int $viewerUserId): array
    {
        $creator = self::creatorRow($creatorId);

        if ((int) $creator['user_id'] !== $viewerUserId) {
            throw HttpException::forbidden('You can only preview your own profile.');
        }

        return [
            'creator'    => CreatorService::profile($creatorId, $viewerUserId),
            'visibility' => self::visibility($creatorId),
            'share'      => self::sharePayload($creatorId, $viewerUserId),
        ];
    }

    /**
     * The columns every method here needs, fetched once.
     *
     * @return array<string,mixed>
     */
    private static function creatorRow(int $creatorId): array
    {
        $creator = Database::selectOne(
            'SELECT `id`, `user_id`, `handle`, `display_name`, `headline`, `status`, `is_public`
               FROM `creators`
              WHERE `id` = :id AND `deleted_at` IS NULL',
            ['id' => $creatorId]
        );

        if ($creator === null) {
            throw HttpException::notFound('Creator not found.');
        }

        return $creator;
    }
}
